-- Bootstrap CMS analytics objects for Snowflake Cortex Analyst.
-- Run the role and warehouse statements as ACCOUNTADMIN or a similarly privileged role.

CREATE ROLE IF NOT EXISTS CMS_CORTEX_ROLE;
CREATE ROLE IF NOT EXISTS CMS_API_ROLE;
CREATE ROLE IF NOT EXISTS CMS_DEVELOPER_ROLE;

CREATE WAREHOUSE IF NOT EXISTS CMS_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS CMS_DB;
CREATE SCHEMA IF NOT EXISTS CMS_DB.ANALYTICS;
CREATE SCHEMA IF NOT EXISTS CMS_DB.CORTEX;

GRANT USAGE ON WAREHOUSE CMS_WH TO ROLE CMS_CORTEX_ROLE;
GRANT USAGE ON WAREHOUSE CMS_WH TO ROLE CMS_API_ROLE;
GRANT USAGE ON WAREHOUSE CMS_WH TO ROLE CMS_DEVELOPER_ROLE;
GRANT USAGE ON DATABASE CMS_DB TO ROLE CMS_CORTEX_ROLE;
GRANT USAGE ON DATABASE CMS_DB TO ROLE CMS_API_ROLE;
GRANT USAGE ON DATABASE CMS_DB TO ROLE CMS_DEVELOPER_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CMS_DB TO ROLE CMS_CORTEX_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CMS_DB TO ROLE CMS_API_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CMS_DB TO ROLE CMS_DEVELOPER_ROLE;

USE ROLE CMS_DEVELOPER_ROLE;
USE WAREHOUSE CMS_WH;
USE DATABASE CMS_DB;
USE SCHEMA CMS_DB.ANALYTICS;

CREATE OR REPLACE TABLE PROVIDERS (
  PROVIDER_ID         VARCHAR(20) NOT NULL PRIMARY KEY,
  PROVIDER_NAME       VARCHAR(200) NOT NULL,
  PROVIDER_TYPE       VARCHAR(100),
  SPECIALTY           VARCHAR(150),
  STATE               CHAR(2),
  CITY                VARCHAR(100),
  ZIP_CODE            VARCHAR(10),
  MEDICARE_ENROLLMENT DATE,
  NPI                 VARCHAR(10),
  UPDATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE CLAIMS (
  CLAIM_ID          VARCHAR(30) NOT NULL PRIMARY KEY,
  PROVIDER_ID       VARCHAR(20) REFERENCES PROVIDERS(PROVIDER_ID),
  CLAIM_DATE        DATE NOT NULL,
  SERVICE_DATE      DATE,
  CLAIM_TYPE        VARCHAR(50),
  DIAGNOSIS_CODE    VARCHAR(10),
  PROCEDURE_CODE    VARCHAR(10),
  BILLED_AMOUNT     NUMBER(15,2),
  ALLOWED_AMOUNT    NUMBER(15,2),
  PAID_AMOUNT       NUMBER(15,2),
  PATIENT_AGE_GROUP VARCHAR(20),
  PATIENT_STATE     CHAR(2),
  UPDATED_AT        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE DRUG_UTILIZATION (
  RECORD_ID         NUMBER AUTOINCREMENT PRIMARY KEY,
  PROVIDER_ID       VARCHAR(20) REFERENCES PROVIDERS(PROVIDER_ID),
  DRUG_NAME         VARCHAR(200),
  GENERIC_NAME      VARCHAR(200),
  NDC_CODE          VARCHAR(11),
  CLAIM_YEAR        NUMBER(4),
  CLAIM_COUNT       NUMBER,
  BENEFICIARY_COUNT NUMBER,
  TOTAL_DRUG_COST   NUMBER(18,2),
  UPDATED_AT        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE QUALITY_MEASURES (
  MEASURE_ID       VARCHAR(20) NOT NULL,
  PROVIDER_ID      VARCHAR(20) REFERENCES PROVIDERS(PROVIDER_ID),
  MEASURE_NAME     VARCHAR(300),
  MEASURE_DOMAIN   VARCHAR(100),
  PERFORMANCE_RATE NUMBER(5,2),
  NATIONAL_AVERAGE NUMBER(5,2),
  STAR_RATING      NUMBER(1),
  REPORTING_YEAR   NUMBER(4),
  UPDATED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (MEASURE_ID, PROVIDER_ID, REPORTING_YEAR)
);

